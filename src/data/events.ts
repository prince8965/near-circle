export const SEED_EVENTS: Event[] = seeds.map((s) => {
  const loc = getLocality(s.localityId)
  // Spread venues slightly around the locality centre so map pins differ.
  const jitter = (n: number) => ((Array.from(s.id).reduce((a, c) => a + c.charCodeAt(0), 0) * (n + 3)) % 100) / 100 - 0.5
  return {
    ...s,
    ownerId: s.ownerId ?? 'u-demo',
    lat: loc.lat + jitter(1) * 0.012,
    lng: loc.lng + jitter(2) * 0.012,
    status: 'published' as const,
    isDemo: true,
  }
})
