/**
 * DEMO CONTENT. Events across Mumbai & Navi Mumbai.
 * Dates are generated relative to the first time the app runs, so the demo always has upcoming events.
 */
function at(dayOffset: number, hour: number, minute = 0, durationHours = 2): { startsAt: string; endsAt: string } {
  const start = new Date()
  start.setDate(start.getDate() + dayOffset)
  start.setHours(hour, minute, 0, 0)
  const end = new Date(start.getTime() + durationHours * 3600_000)
  return { startsAt: start.toISOString(), endsAt: end.toISOString() }
}

